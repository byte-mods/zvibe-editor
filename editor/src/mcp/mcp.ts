function createMcpActionOptions(editor: Editor): IMCPActionOptions {
	const fallbackInspector = {
		setEditedObject: (_object: unknown): void => undefined,
		forceUpdate: (): void => undefined,
	};
	const layout = new Proxy(editor.layout, {
		get: (target, property, receiver) => {
			if (property === "inspector") {
				return target.inspector ?? fallbackInspector;
			}
			return Reflect.get(target, property, receiver);
		},
	});
	const safeEditor = new Proxy(editor, {
		get: (target, property, receiver) => {
			if (property === "layout") {
				return layout;
			}
			const value = Reflect.get(target, property, receiver);
			return typeof value === "function" ? value.bind(target) : value;
		},
	});
	return { editor: safeEditor };
}

/**
 * Initializes the editor MCP HTTP server.
 * Resilient: if the port is already in use (e.g. a second editor window), the error is caught
 * and logged in the editor console instead of crashing the application.
 * @param editor defines the reference to the editor.
 * @returns a disposer that releases the HTTP listener and collaboration gateway.
 */
export function initializeMcpServer(editor: Editor): () => void {
	let disposed = false;
	void (async () => {
		await waitUntil(() => editor.state.projectPath);
		await initializeRemoteCollaborationGateway(editor, MCPEndpoints);
		if (disposed) {
			await shutdownRemoteCollaborationGateway();
		}
	})().catch((error) => {
		if (disposed) {
			return;
		}
		editor.layout.console.error(`Remote collaboration gateway failed to initialize: ${error instanceof Error ? error.message : String(error)}`);
	});
	const server = createServer(async (req, res) => {
		let data: IEditorMCPDataType;
		try {
			data = await new Promise<IEditorMCPDataType>((resolve, reject) => {
				let body = "";
				let byteLength = 0;
				let rejected = false;

				req.on("data", (chunk: Buffer) => {
					if (rejected) {
						return;
					}
					byteLength += chunk.byteLength;
					if (byteLength > MAXIMUM_MCP_REQUEST_BYTES) {
						rejected = true;
						reject(new Error(`MCP request body exceeds the ${MAXIMUM_MCP_REQUEST_BYTES / (1024 * 1024)} MiB limit.`));
						return;
					}
					body += chunk.toString();
				});
				req.on("end", () => {
					if (rejected) {
						return;
					}
					try {
						resolve(parseMcpRequestBody(body));
					} catch (error) {
						reject(error);
					}
				});
				req.on("error", reject);
			});
		} catch (e) {
			res.writeHead(400, { "Content-Type": "application/json" });
			res.end(JSON.stringify({ error: e instanceof Error ? e.message : String(e) }));
			return;
		}

		const action = MCPEndpoints[data.endpoint];

		if (!action) {
			res.writeHead(404, { "Content-Type": "application/json" });
			res.end(JSON.stringify({ error: `Unknown endpoint: ${data.endpoint}` }));
			return;
		}

		try {
			await authorizeProjectCollaborationRequest(data.endpoint, data, { editor });
			const result = await action(editor.layout.preview.scene, data, createMcpActionOptions(editor));
			await publishRemoteCollaborationOperation(data.endpoint, true, data.collaborationToken, { editor }, "Editor action completed.");

			res.writeHead(200, { "Content-Type": "application/json" });
			res.end(JSON.stringify(result ?? null));
		} catch (e) {
			await publishRemoteCollaborationOperation(data.endpoint, false, data.collaborationToken, { editor }, e instanceof Error ? e.message : String(e)).catch(() => undefined);
			res.writeHead(500, { "Content-Type": "application/json" });
			res.end(JSON.stringify({ error: e instanceof Error ? e.message : String(e) }));
		}
	});

	let listenAttempt = 0;
	const maximumListenAttempts = 20;
	let retryTimer: ReturnType<typeof setTimeout> | null = null;
	const dispose = (): void => {
		if (disposed) {
			return;
		}
		disposed = true;
		if (retryTimer) {
			clearTimeout(retryTimer);
			retryTimer = null;
		}
		window.removeEventListener("beforeunload", dispose);
		window.removeEventListener("pagehide", dispose);
		if (server.listening) {
			server.close();
			server.closeAllConnections();
		}
		void shutdownRemoteCollaborationGateway().catch(() => undefined);
		const scene = editor.layout.preview.scene;
		if (scene) {
			shutdownTesting(scene);
			shutdownProjectCodeTests(scene);
			shutdownProjectAuditor(scene);
			shutdownPlatformPlayerRuntime(scene);
			shutdownAssetStreamingRuntime(scene);
		}
		// Connected-player profiling owns a Device Lab reservation, so release it before the transport closes.
		void (async (): Promise<void> => {
			if (scene) {
				await shutdownProfiling(scene, { editor }).catch(() => undefined);
			}
			await shutdownGenerativeAssets(editor).catch(() => undefined);
			await shutdownMlTraining(editor).catch(() => undefined);
			await shutdownRuntimeAi(editor).catch(() => undefined);
			await shutdownNetworking().catch(() => undefined);
			await shutdownMobileWorkflows().catch(() => undefined);
			shutdownConsoleServerWorkflows();
			await shutdownDeviceLab().catch(() => undefined);
		})();
	};
	const listen = (): void => {
		if (disposed) {
			return;
		}
		listenAttempt++;
		server.listen(MCPServerPort, "127.0.0.1");
	};
	server.on("listening", () => {
		if (disposed) {
			server.close();
			server.closeAllConnections();
			return;
		}
		editor.layout.console.log(`MCP Server is listening on port ${MCPServerPort}`);
	});
	server.on("error", (e: NodeJS.ErrnoException) => {
		if (disposed) {
			return;
		}
		if (e.code === "EADDRINUSE" && listenAttempt < maximumListenAttempts) {
			retryTimer = setTimeout(() => {
				retryTimer = null;
				listen();
			}, 250);
			return;
		}
		editor.layout.console.error(`MCP Server failed to start after ${listenAttempt} attempt(s): ${e.message}`);
	});
	window.addEventListener("beforeunload", dispose, { once: true });
	window.addEventListener("pagehide", dispose, { once: true });
	listen();
	return dispose;
}
